import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { build, transform } from 'esbuild';
import { compileModule } from 'svelte/compiler';
import type { PresentationData } from '@office-kit/pptx';
import type * as PptxModule from '@office-kit/pptx';
import type * as DocumentModule from '../src/core/document.svelte.ts';
import type { ExternalHistoryAdapter } from '../src/core/external-history.ts';

const built = await build({
  stdin: {
    contents: `export { EditorDocument } from './src/core/document.svelte.ts';
      export { createPresentation, addTitleSlide, getSlides, getSlideText, savePresentation } from '@office-kit/pptx';
      export { serializationCount } from 'history-save-probe';`,
    resolveDir: fileURLToPath(new URL('..', import.meta.url)),
  },
  bundle: true,
  write: false,
  platform: 'node',
  format: 'esm',
  plugins: [
    {
      name: 'editor-runes-and-history-probe',
      setup(builder) {
        builder.onResolve({ filter: /^history-save-probe$/ }, () => ({
          path: 'history-save-probe',
          namespace: 'probe',
        }));
        builder.onLoad({ filter: /.*/, namespace: 'probe' }, () => ({
          contents: `import { savePresentation as save } from '@office-kit/pptx';
          export let serializationCount = 0;
          export function savePresentation(pres) { serializationCount++; return save(pres); }`,
          resolveDir: fileURLToPath(new URL('..', import.meta.url)),
        }));
        builder.onLoad({ filter: /\.svelte\.ts$/ }, async ({ path }) => {
          let source = await readFile(path, 'utf8');
          if (path.endsWith('document.svelte.ts')) {
            source = source.replace('  savePresentation,', '');
            source += '\nimport { savePresentation } from "history-save-probe";';
          }
          const stripped = await transform(source, { loader: 'ts' });
          return {
            contents: compileModule(stripped.code, { filename: path, generate: 'client' }).js.code,
          };
        });
      },
    },
  ],
});
const output = built.outputFiles[0];
assert.ok(output);
// The compiled module has the same exports as these sources; its URL is generated by esbuild.
const runtime: typeof DocumentModule & typeof PptxModule & { serializationCount: number } =
  await import(`data:text/javascript;base64,${Buffer.from(output.text).toString('base64')}`);
const {
  EditorDocument,
  createPresentation,
  addTitleSlide,
  getSlides,
  getSlideText,
  savePresentation,
} = runtime;

function project(titles: readonly string[]): PresentationData {
  const pres = createPresentation();
  for (const title of titles) addTitleSlide(pres, title);
  return pres;
}

function titles(pres: PresentationData): string[] {
  return getSlides(pres).map(getSlideText);
}

function history() {
  let states: string[][] = [];
  let cursor = 0;
  let reject = false;
  const commits: { label: string; source: string; slideIndex: number }[] = [];
  const restores: string[] = [];
  const adapter: ExternalHistoryAdapter = {
    reset(pres) {
      states = [titles(pres)];
      cursor = 0;
    },
    commit(pres, context) {
      if (reject) throw new Error('Unsupported projection');
      states = [...states.slice(0, cursor + 1), titles(pres)];
      cursor++;
      commits.push(context);
    },
    restore(action) {
      restores.push(action);
      if (action === 'undo') cursor--;
      if (action === 'redo') cursor++;
      const state = states[cursor];
      assert.ok(state);
      return project(state);
    },
    get canUndo() {
      return cursor > 0;
    },
    get canRedo() {
      return cursor < states.length - 1;
    },
    get undoLabel() {
      return cursor > 0 ? 'External undo' : null;
    },
    get redoLabel() {
      return cursor < states.length - 1 ? 'External redo' : null;
    },
  };
  return {
    adapter,
    commits,
    restores,
    reject() {
      reject = true;
    },
    states: () => states,
  };
}

test('external history owns initial, transaction, gesture, settings, undo/redo, new and open without byte snapshots', async () => {
  const count = runtime.serializationCount;
  const host = history();
  const doc = new EditorDocument(host.adapter);
  assert.equal(runtime.serializationCount, count);
  for (const source of ['user', 'agent', 'source'] as const) {
    doc.transact(source, () => addTitleSlide(doc.pres, source), source);
  }
  doc.applyLive(() => addTitleSlide(doc.pres, 'Frame 1'));
  doc.applyLive(() => addTitleSlide(doc.pres, 'Frame 2'));
  assert.equal(host.commits.length, 3);
  doc.commit('Gesture');
  doc.setDocumentSetting(() => addTitleSlide(doc.pres, 'Setting'));
  assert.deepEqual(
    host.commits.map(({ source }) => source),
    ['user', 'agent', 'source', 'user', 'user'],
  );
  assert.equal(host.commits[3]?.label, 'Gesture');
  assert.equal(doc.undoLabel, 'External undo');
  doc.selectShape(99, 999);
  await doc.undo();
  assert.equal(doc.selection.kind, 'none');
  assert.ok(doc.selection.slideIndex < getSlides(doc.pres).length);
  assert.equal(doc.canRedo, true);
  assert.equal(doc.redoLabel, 'External redo');
  await doc.redo();
  assert.equal(titles(doc.pres).at(-1), 'Setting');
  doc.resetBlank();
  assert.equal(doc.canUndo, false);
  const bytes = await savePresentation(project(['Opened']));
  await doc.loadBytes(bytes, 'opened.pptx');
  assert.deepEqual(titles(doc.pres), ['Opened']);
  assert.equal(doc.canUndo, false);
  assert.equal(runtime.serializationCount, count);
});

test('cancel and synchronous failures restore canonical projection and preserve history/dirty state', async () => {
  const host = history();
  const doc = new EditorDocument(host.adapter);
  const initial = titles(doc.pres);
  doc.applyLive(() => addTitleSlide(doc.pres, 'Transient'));
  await doc.cancelLive();
  assert.deepEqual(titles(doc.pres), initial);
  assert.equal(doc.dirty, false);
  doc.applyLive(() => addTitleSlide(doc.pres, 'Transient'));
  assert.throws(
    () =>
      doc.applyLive(() => {
        throw new Error('Broken frame');
      }),
    /Broken frame/,
  );
  assert.deepEqual(titles(doc.pres), initial);
  assert.equal(doc.liveEditing, false);
  assert.equal(doc.dirty, false);
  host.reject();
  assert.throws(
    () => doc.transact('Rejected', () => addTitleSlide(doc.pres, 'Partial')),
    /Unsupported projection/,
  );
  assert.deepEqual(titles(doc.pres), initial);
  assert.deepEqual(host.states(), [initial]);
  assert.equal(doc.canUndo, false);
  assert.deepEqual(host.restores, ['cancel', 'rollback', 'rollback']);
});

test('rejected gestures and settings preserve the prior clean canonical state', () => {
  for (const kind of ['gesture', 'setting']) {
    const host = history();
    const doc = new EditorDocument(host.adapter);
    const initial = titles(doc.pres);
    host.reject();
    if (kind === 'gesture') {
      doc.applyLive(() => addTitleSlide(doc.pres, 'Partial'));
      assert.throws(() => doc.commit('Rejected gesture'), /Unsupported projection/);
    } else {
      assert.throws(
        () => doc.setDocumentSetting(() => addTitleSlide(doc.pres, 'Partial')),
        /Unsupported projection/,
      );
    }
    assert.deepEqual(titles(doc.pres), initial);
    assert.deepEqual(host.states(), [initial]);
    assert.equal(doc.dirty, false);
    assert.equal(doc.liveEditing, false);
    assert.equal(doc.version, doc.committedVersion);
  }
});

test('external transactions and settings cannot interleave with a live gesture', async () => {
  for (const dirty of [false, true]) {
    const host = history();
    const doc = new EditorDocument(host.adapter);
    if (dirty) doc.transact('Existing edit', () => addTitleSlide(doc.pres, 'Existing edit'));
    const committed = titles(doc.pres);
    const commits = host.commits.length;
    doc.applyLive(() => addTitleSlide(doc.pres, 'Transient'));
    let ran = false;
    assert.throws(
      () =>
        doc.transact('Async paste', () => {
          ran = true;
        }),
      /current gesture/,
    );
    assert.throws(
      () =>
        doc.setDocumentSetting(() => {
          ran = true;
        }),
      /current gesture/,
    );
    assert.equal(ran, false);
    assert.equal(doc.liveEditing, true);
    assert.equal(host.commits.length, commits);
    await doc.cancelLive();
    assert.deepEqual(titles(doc.pres), committed);
    assert.equal(doc.dirty, dirty);
    assert.equal(host.commits.length, commits);
  }
});

test('rejected undo and New reset restore the previous canonical projection', async () => {
  const host = history();
  const doc = new EditorDocument(host.adapter);
  doc.transact('Accepted', () => addTitleSlide(doc.pres, 'Accepted'));
  const accepted = titles(doc.pres);
  const restore = host.adapter.restore;
  host.adapter.restore = (action, pres) => {
    if (action === 'undo') throw new Error('Undo refused');
    return restore(action, pres);
  };
  await assert.rejects(doc.undo(), /Undo refused/);
  assert.deepEqual(titles(doc.pres), accepted);
  assert.equal(doc.canUndo, true);
  host.adapter.reset = () => {
    throw new Error('Reset refused');
  };
  doc.applyLive(() => addTitleSlide(doc.pres, 'Partial'));
  assert.throws(() => doc.resetBlank(), /Reset refused/);
  assert.deepEqual(titles(doc.pres), accepted);
  assert.equal(doc.liveEditing, false);
  assert.equal(doc.fileName, 'Untitled.pptx');
});

test('a failed external rollback blocks edits/saves and New recovers', async () => {
  const host = history();
  const doc = new EditorDocument(host.adapter);
  host.adapter.restore = () => {
    throw new Error('Projection unavailable');
  };
  assert.throws(
    () =>
      doc.transact('Broken', () => {
        throw new Error('Edit failed');
      }),
    AggregateError,
  );
  assert.throws(() => doc.transact('Blocked', () => {}), /could not be undone/);
  await assert.rejects(doc.toBytes(), /could not be undone/);
  doc.resetBlank();
  doc.transact('Recovered', () => addTitleSlide(doc.pres, 'Recovered'));
  assert.equal(titles(doc.pres).at(-1), 'Recovered');
});

test('default history still seeds snapshots and supports undo/redo', async () => {
  const count = runtime.serializationCount;
  const doc = new EditorDocument();
  assert.equal(runtime.serializationCount, count + 1);
  doc.transact('Default', () => addTitleSlide(doc.pres, 'Default'));
  assert.equal(runtime.serializationCount, count + 2);
  await doc.undo();
  assert.deepEqual(titles(doc.pres), ['Untitled presentation']);
  await doc.redo();
  assert.equal(titles(doc.pres).at(-1), 'Default');
});

test('external refresh projects a host acceptance without committing or resetting history', async () => {
  const host = history();
  const doc = new EditorDocument(host.adapter);
  const events: string[] = [];
  doc.onChange = (source) => events.push(source);
  host.adapter.commit(project(['Host accepted AI']), {
    label: 'AI Accept',
    source: 'agent',
    slideIndex: 0,
  });
  const entries = host.states().length;
  const snapshots = runtime.serializationCount;
  doc.refreshFromExternalHistory();
  assert.deepEqual(titles(doc.pres), ['Host accepted AI']);
  assert.equal(host.states().length, entries);
  assert.equal(host.commits.length, 1);
  assert.equal(runtime.serializationCount, snapshots);
  assert.equal(doc.canUndo, true);
  assert.equal(doc.dirty, true);
  assert.deepEqual(events, ['agent']);
  await doc.undo();
  assert.deepEqual(titles(doc.pres), ['Untitled presentation']);
  doc.applyLive(() => {});
  assert.throws(() => doc.refreshFromExternalHistory(), /current gesture/);
  await doc.cancelLive();
  assert.throws(() => new EditorDocument().refreshFromExternalHistory(), /not configured/);
});
